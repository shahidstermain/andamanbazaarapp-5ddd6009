## 🔥 Drifters Lounge Bar — Hotel Driftwood

The party. Currently ranked among the **top pubs in Port Blair** (Restaurant Guru #2 of 77) with a price band around ₹400–₹1,600 per person. This is where the dance floor actually moves — DJ sets, loud music, ladies' nights with **free shots for ladies** on select evenings, and a crowd that doesn't thin out till late. Walk in early on Fri/Sat or you'll be queueing.

