The classy one. An elegant lounge bar inside **Hotel Shompen** (Symphony Resorts) with live music most evenings, refreshing cocktails and that slow, candle-lit vibe you want when you're not in the mood to shout over a DJ. Great for couples and small groups easing into the night.

