## 🌅 Amaya Lounge — Sea Shell, Marine Hill

The rooftop. In-house bar on top of **Sea Shell, Marine Hill** with proper sea views, candle-lit tables and a small but solid menu (their seafood platter and flaming shooters do the heavy lifting). Best for couples and slow evenings when you want a view, not a dance floor.

- **Where:** Sea Shell, Marine Hill, Port Blair
- **Google Maps:** [Amaya Lounge, Sea Shell](https://www.google.com/maps/search/?api=1&query=Amaya+Lounge+Sea+Shell+Marine+Hill+Port+Blair)
- **Best for:** Rooftop views, couples, seafood + cocktails
- **Source:** [go2andaman.com](https://www.go2andaman.com/restaurant/amaya-lounge-seashell-port-blair/)

## 🥃 Luxx Pub & Lounge — opp. Chinmaya Mission

The upmarket pub. Ranked **#3 of 77 pubs & bars in Port Blair** on Restaurant Guru, slightly higher price band (~₹940–₹2,400 per person) and a grill-leaning menu. Good middle-ground between Drifters' party energy and Love Garden's quiet — well-lit, well-stocked, decent for a longer sit-down evening.

- **Where:** Opp. Chinmaya Mission, Port Blair
- **Google Maps:** [Luxx Pub & Lounge, Port Blair](https://www.google.com/maps/search/?api=1&query=Luxx+Pub+Lounge+Port+Blair)
- **Best for:** Grill, longer evenings, upmarket pub feel
- **Source:** [restaurant-guru.in](https://restaurant-guru.in/Luxx-Pub-and-Lounge-Port-Blair)

