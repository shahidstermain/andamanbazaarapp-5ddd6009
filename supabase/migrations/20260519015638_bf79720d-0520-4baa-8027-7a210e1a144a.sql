## 🌶️🍋 Junglee Mirchi / Nimbu Pani Pub — Caddlegunj & Junglighat

Same team, two faces. **Junglee Mirchi** (NH-4, Caddlegunj) is the full combo — resort, multi-cuisine restaurant, pub and a small waterpark — about a 20–30 min drive from central Port Blair. **Nimbu Pani Pub** in Junglighat is the same crew's city-side outlet: lower-key, neighbourhood vibe, no pretension. Junglee Mirchi is great for groups doing a full day (afternoon swim → long lunch → pub night); Nimbu Pani is the honest local stop if you're closing out a Port Blair nightlife loop. The food at both is genuinely good — not an afterthought to the bar.

