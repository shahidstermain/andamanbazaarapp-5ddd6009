## Before you head out — practical notes

- **Dry days** apply across the islands: 1st of every month, national holidays and election days, no alcohol service.
- Most venues wind down between **11:00 PM and 11:30 PM**. Drifters typically stretches the latest.
- Carry **photo ID** — most bars check.
- **Pre-book your ride back**, especially from Caddlegunj. Autos and cabs get scarce after midnight.

